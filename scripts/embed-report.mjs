#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { gzipSync } from "node:zlib";

const root = path.resolve(import.meta.dirname, "..");
const source = path.join(root, "web", "dist", "report.html");
const target = path.join(root, "src", "render", "report-template.generated.ts");

if (!fs.existsSync(source)) {
  process.stderr.write(`Missing ${source}; run "npm --prefix web run build" first.\n`);
  process.exit(1);
}

const html = fs.readFileSync(source, "utf8");
if (!html.includes('id="tsray-data"') || !html.includes("__TSRAY_REPORT_DATA__")) {
  process.stderr.write("Built report is missing the tsray-data placeholder script tag.\n");
  process.exit(1);
}

const gzip = gzipSync(Buffer.from(html, "utf8"), { level: 9 });
const base64 = gzip.toString("base64");
const chunks = base64.match(/.{1,120}/g) ?? [];

const output = `/**
 * Generated by scripts/embed-report.mjs from web/dist/report.html.
 * Run \`npm run build:web\` to refresh this file. Do not edit manually.
 */
export const REPORT_TEMPLATE_GZIP_BASE64 = [
${chunks.map((chunk) => `  "${chunk}",`).join("\n")}
].join("");
`;

fs.writeFileSync(target, output, "utf8");
process.stdout.write(
  `Embedded ${path.relative(root, source)} (${html.length} bytes) as ${gzip.length} gzip bytes in ${path.relative(root, target)}\n`
);
